const resources: Record<LanguageCode, Record<TranslationKey, string>> = { "fa-AF": fa, "ps-AF": ps, en };

export function isRtlLanguage(language: LanguageCode): boolean {
  return language === "fa-AF" || language === "ps-AF";
}

export function translate(language: LanguageCode, key: TranslationKey, params?: Record<string, string | number>): string {
  let value: string = resources[language][key] ?? en[key];
  if (!params) return value;
  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function getLanguage(language: LanguageCode) {
  return languages.find((item) => item.code === language) ?? languages[0];
}
